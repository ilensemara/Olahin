// Fallback route to serve the built Vue SPA frontend for any non-API routes
Route::any('{any}', function () {
    $indexPath = public_path('index.html');
    if (file_exists($indexPath)) {
        return file_get_contents($indexPath);
    }
    return view('welcome');
})->where('any', '.*');
